import * as THREE from 'three';
import { initManifold } from '../src/csg.js';
console.log('manifold', await initManifold());
import { getGeometry, massProps, nodeMatrix, buildRegions } from '../src/geometry.js';
const ctx = { seg: 48, meshStore: new Map() };
const vol = (n) => massProps(getGeometry(n, ctx), nodeMatrix(n)).volume;
const N = (type, params, extra={}) => ({ id:'x', type, params, pos:[0,0,0], rot:[0,0,0], scl:[1,1,1], ...extra });
const box = N('box',{w:40,h:20,d:10});
console.log('box', vol(box), 'expect 8000');
const ext = N('extrude',{profiles:[{t:'rect',x:0,y:0,w:40,h:20},{t:'circle',x:20,y:10,r:5}],depth:10,dir:1});
console.log('extrude w/ hole', vol(ext).toFixed(1), 'expect', (8000-Math.PI*25*10).toFixed(1));
const rev = N('revolve',{profiles:[{t:'rect',x:10,y:0,w:5,h:20}],angle:360,axis:'y'});
console.log('revolve tube', vol(rev).toFixed(1), 'expect', (Math.PI*(225-100)*20).toFixed(1));
const rev2 = N('revolve',{profiles:[{t:'rect',x:-15,y:0,w:5,h:20}],angle:90,axis:'y'});
console.log('revolve 90 neg', vol(rev2).toFixed(1), 'expect', (Math.PI*(225-100)*20/4).toFixed(1));
const revx = N('revolve',{profiles:[{t:'rect',x:0,y:10,w:20,h:5}],angle:360,axis:'x'});
console.log('revolve x', vol(revx).toFixed(1), 'expect', (Math.PI*(225-100)*20).toFixed(1));
const tube = N('tube',{ro:20,ri:15,h:40});
console.log('tube', vol(tube).toFixed(1), 'expect', (Math.PI*(400-225)*40).toFixed(1));
const prism = N('prism',{r:20,n:6,h:10}); console.log('prism', vol(prism).toFixed(1), 'expect', (3*Math.sqrt(3)/2*400*10).toFixed(1));
const wedge = N('wedge',{w:40,h:30,d:10}); console.log('wedge', vol(wedge), 'expect 6000');
const cyl = N('cylinder',{r:5,h:50},{pos:[0,0,0]});
const b = N('boolean',{}, {op:'subtract', children:[N('box',{w:40,h:40,d:40}), cyl]});
let t=performance.now(); console.log('box-cyl', vol(b).toFixed(1), 'approx', (64000-Math.PI*25*40).toFixed(1), (performance.now()-t).toFixed(0)+'ms');
const u = N('boolean',{}, {op:'union', children:[N('box',{w:40,h:40,d:40}), N('box',{w:40,h:40,d:40},{pos:[20,0,0]})]});
console.log('union overlap', vol(u).toFixed(1), 'expect 96000');
const u2 = N('boolean',{}, {op:'union', children:[N('box',{w:40,h:40,d:40}), N('box',{w:40,h:40,d:40},{pos:[40,0,0]})]});
console.log('union touching', vol(u2).toFixed(1), 'expect 128000', 'tris', getGeometry(u2,ctx).attributes.position.count/3);
const m = N('boolean',{}, {op:'union', children:[N('box',{w:40,h:40,d:40}), N('box',{w:40,h:40,d:40},{pos:[40,0,0], scl:[-1,1,1]})]});
console.log('union mirrored', vol(m).toFixed(1), 'expect 128000');
const ov = N('extrude',{profiles:[{t:'rect',x:0,y:0,w:40,h:20},{t:'circle',x:40,y:10,r:10}],depth:10,dir:1});
console.log('overlapping profiles', vol(ov).toFixed(1), 'approx', (8000+Math.PI*100*10/2).toFixed(1));
const slot = N('extrude',{profiles:[{t:'slot',x1:0,y1:0,x2:20,y2:0,r:5}],depth:10,dir:0});
console.log('slot', vol(slot).toFixed(1), 'approx', ((20*10+Math.PI*25)*10).toFixed(1));
// cut extrude through nested booleans
const cut = N('extrude',{profiles:[{t:'circle',x:0,y:0,r:5}],depth:10,dir:-1,extra:0.02},{pos:[0,20,0],rot:[-90,0,0]});
const b2 = N('boolean',{}, {op:'subtract', children:[N('box',{w:40,h:40,d:40}), cut]});
console.log('cut on top face', vol(b2).toFixed(1), 'approx', (64000-Math.PI*25*10).toFixed(1));
const sph = N('sphere',{r:20}); console.log('sphere', vol(sph).toFixed(0), 'approx', (4/3*Math.PI*8000).toFixed(0));
const tor = N('torus',{R:25,r:7}); console.log('torus', vol(tor).toFixed(0), 'approx', (2*Math.PI*Math.PI*25*49).toFixed(0));
const s2 = N('boolean',{}, {op:'subtract', children:[sph, N('cylinder',{r:5,h:60})]}); console.log('sphere-cyl', vol(s2).toFixed(0));
const tor2 = N('boolean',{}, {op:'intersect', children:[tor, N('box',{w:100,h:100,d:100},{pos:[50,0,0]})]}); console.log('torus half', vol(tor2).toFixed(0), 'approx', (Math.PI*Math.PI*25*49).toFixed(0));
